const LANGS = ['en', 'zh', 'fr', 'id', 'vi', 'hi', 'ar', 'ur']

for (const lang of LANGS) {
  const filePath = path.join(MESSAGES_DIR, `${lang}.json`)
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'))

  // Inject dashboard keys
  const dashKeys = NEW_DASHBOARD_KEYS[lang]
  if (dashKeys) {
    data.dashboard = { ...data.dashboard, ...dashKeys }
  }

  // Inject alpha.signals keys
  const sigKeys = NEW_SIGNAL_KEYS[lang]
  if (sigKeys) {
    data.alpha = data.alpha || {}
    data.alpha.signals = { ...data.alpha.signals, ...sigKeys }
  }

  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8')
  console.log(`✓ ${lang}.json updated`)
}

console.log('Done.')
